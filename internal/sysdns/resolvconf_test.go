//go:build linux || darwin

package sysdns

import (
	"net/netip"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

var loopback = []netip.Addr{netip.MustParseAddr("127.0.0.1"), netip.MustParseAddr("::1")}

const dhcpConf = "# Generated by NetworkManager\nsearch home corp.example\nnameserver 192.168.1.254\nnameserver fe80::1%eth0\n"

func newResolvConf(t *testing.T) (*ResolvConf, string) {
	t.Helper()
	dir := t.TempDir()
	return &ResolvConf{Path: filepath.Join(dir, "resolv.conf"), StatePath: filepath.Join(dir, "state", "resolv.conf.json")}, dir
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestResolvConfFileRoundTrip(t *testing.T) {
	r, _ := newResolvConf(t)
	if err := os.WriteFile(r.Path, []byte(dhcpConf), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := r.Apply(loopback); err != nil {
		t.Fatal(err)
	}
	got := read(t, r.Path)
	if !strings.Contains(got, "nameserver 127.0.0.1\nnameserver ::1\nsearch home corp.example\n") || strings.Contains(got, "192.168.1.254") {
		t.Fatalf("applied resolv.conf:\n%s", got)
	}
	if ok, err := r.Applied(loopback); !ok || err != nil {
		t.Fatalf("Applied = %v, %v", ok, err)
	}
	n, err := r.Network()
	if err != nil {
		t.Fatal(err)
	}
	want := []netip.Addr{netip.MustParseAddr("192.168.1.254"), netip.MustParseAddr("fe80::1%eth0")}
	if !slices.Equal(n.Servers, want) || !slices.Equal(n.Domains, []string{"home", "corp.example"}) {
		t.Fatalf("Network = %+v", n)
	}
	if err := r.Apply(loopback); err != nil { // idempotent: the original must not become OffLok's file
		t.Fatal(err)
	}
	if err := r.Restore(); err != nil {
		t.Fatal(err)
	}
	if got := read(t, r.Path); got != dhcpConf {
		t.Fatalf("restored:\n%s", got)
	}
	if _, err := os.Stat(r.StatePath); !os.IsNotExist(err) {
		t.Fatal("state file left behind")
	}
}

func TestResolvConfSymlinkRoundTrip(t *testing.T) {
	r, dir := newResolvConf(t)
	target := filepath.Join(dir, "managed.conf")
	if err := os.WriteFile(target, []byte(dhcpConf), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, r.Path); err != nil {
		t.Fatal(err)
	}
	if err := r.Apply(loopback); err != nil {
		t.Fatal(err)
	}
	if fi, _ := os.Lstat(r.Path); fi.Mode()&os.ModeSymlink != 0 {
		t.Fatal("still a symlink after Apply")
	}
	if got := read(t, target); got != dhcpConf {
		t.Fatal("the link target must never be written")
	}
	if err := r.Restore(); err != nil {
		t.Fatal(err)
	}
	if got, err := os.Readlink(r.Path); err != nil || got != target {
		t.Fatalf("Readlink = %q, %v", got, err)
	}
}

func TestResolvConfRewrittenByDHCP(t *testing.T) {
	r, _ := newResolvConf(t)
	if err := os.WriteFile(r.Path, []byte(dhcpConf), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := r.Apply(loopback); err != nil {
		t.Fatal(err)
	}
	fresh := "nameserver 10.0.0.1\nsearch office\n"
	if err := os.WriteFile(r.Path, []byte(fresh), 0o644); err != nil {
		t.Fatal(err)
	}
	if ok, _ := r.Applied(loopback); ok {
		t.Fatal("Applied after a DHCP rewrite")
	}
	if err := r.Apply(loopback); err != nil {
		t.Fatal(err)
	}
	if n, _ := r.Network(); !slices.Equal(n.Servers, []netip.Addr{netip.MustParseAddr("10.0.0.1")}) {
		t.Fatalf("the rewritten file is the network's latest settings: %+v", n)
	}
	if err := r.Restore(); err != nil {
		t.Fatal(err)
	}
	if got := read(t, r.Path); got != fresh {
		t.Fatalf("restored:\n%s", got)
	}
}

func TestResolvConfRestoreLeavesOthersAlone(t *testing.T) {
	r, _ := newResolvConf(t)
	if err := os.WriteFile(r.Path, []byte(dhcpConf), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := r.Apply(loopback); err != nil {
		t.Fatal(err)
	}
	theirs := "nameserver 9.9.9.9\n"
	if err := os.WriteFile(r.Path, []byte(theirs), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := r.Restore(); err != nil {
		t.Fatal(err)
	}
	if got := read(t, r.Path); got != theirs {
		t.Fatalf("Restore overwrote a file OffLok did not write:\n%s", got)
	}
}

func TestParseResolvConfIgnoresLoopback(t *testing.T) {
	n := ParseResolvConf("nameserver 127.0.0.53\nnameserver ::1\nnameserver 192.168.1.1\nsearch .\n").WithoutLoopback()
	if !slices.Equal(n.Servers, []netip.Addr{netip.MustParseAddr("192.168.1.1")}) || len(n.Domains) != 0 {
		t.Fatalf("%+v", n)
	}
}
